/*
 * Process-identity utility functions (PID/TID/process name).
 */

#include "clog_util.h"
#include <ctype.h>
#include <stdio.h>
#include <string.h>
#include <time.h>
#include <unistd.h>
#include <sys/syscall.h>
#include <sys/types.h>
#ifdef USE_GLIB
#define __packed __attribute__((packed))
#include <glib.h>
#define strlcpy g_strlcpy
#endif

#define CLOG_UTIL_DLT_APP_ID_MAX 4

clog_return_t clog_util_get_process_name(char *out, size_t out_sz)
{
    FILE *fp = NULL;
    size_t len = 0U;

    if (out == NULL || out_sz == 0) {
        return CLOG_RETURN_WRONG_PARAMETER;
    }

    fp = fopen("/proc/self/comm", "r");
    if (fp == NULL) {
	(void)strlcpy(out, "unknown", out_sz);
        return CLOG_RETURN_ERROR;
    }

    if (fgets(out, (int)out_sz, fp) == NULL) {
        (void)fclose(fp);
	(void)strlcpy(out, "unknown", out_sz);
        return CLOG_RETURN_ERROR;
    }
    (void)fclose(fp);

    /* /proc/self/comm output is newline-terminated; strip it. */
    len = strlen(out);
    if (len > 0 && out[len - 1] == '\n') {
        out[len - 1] = '\0';
    }

    if (out[0] == '\0') {
	(void)strlcpy(out, "unknown", out_sz);
        return CLOG_RETURN_ERROR;
    }

    return CLOG_RETURN_OK;
}

long clog_util_get_pid(void)
{
    return (long)getpid();
}

long clog_util_get_tid(void)
{
#ifdef SYS_gettid
    return syscall(SYS_gettid);
#else
    return (long)getpid();
#endif
}

clog_return_t clog_util_build_dlt_app_id(const char *app_id_desc,
                                         char *app_id_out,
                                         size_t app_id_out_sz)
{
    size_t src_len = 0U;
    size_t max_chars = 0U;
    size_t out_len = 0U;
    size_t i = 0U;

    if (app_id_desc == NULL || app_id_out == NULL || app_id_out_sz == 0) {
        return CLOG_RETURN_WRONG_PARAMETER;
    }

    /* Zero-fill so the generated DLT AppID is always NUL-terminated/padded. */
    (void)memset(app_id_out, 0, app_id_out_sz);

    if (app_id_desc[0] == '\0') {
        return CLOG_RETURN_WRONG_PARAMETER;
    }

    max_chars = app_id_out_sz - 1;
    if (max_chars > CLOG_UTIL_DLT_APP_ID_MAX) {
        max_chars = CLOG_UTIL_DLT_APP_ID_MAX;
    }

    if (max_chars == 0) {
        return CLOG_RETURN_WRONG_PARAMETER;
    }

    src_len = strlen(app_id_desc);
    out_len = 0;

    app_id_out[out_len++] = (char)toupper((unsigned char)app_id_desc[0]);

    /* Use the character after each '_'/'-' separator, up to 4 characters. */
    for (i = 1; i < src_len && out_len < max_chars; i++) {
        if ((app_id_desc[i] == '_' || app_id_desc[i] == '-') && ((i + 1) < src_len)) {
            app_id_out[out_len++] = (char)toupper((unsigned char)app_id_desc[i + 1]);
        }
    }

    /* Names without separators (for example "servicemanager") use the first 4 characters. */
    if (out_len == 1) {
        for (i = 1; i < src_len && out_len < max_chars; i++) {
            app_id_out[out_len++] = (char)toupper((unsigned char)app_id_desc[i]);
        }
    }

    return CLOG_RETURN_OK;
}

clog_return_t clog_util_build_auto_identity(char *app_id_out, size_t app_id_out_sz,
                                    char *app_description_out, size_t app_description_out_sz)
{
    char process_name[256] = {0};

    if (app_id_out == NULL || app_id_out_sz == 0 ||
        app_description_out == NULL || app_description_out_sz == 0) {
        return CLOG_RETURN_WRONG_PARAMETER;
    }

    if (clog_util_get_process_name(process_name, sizeof(process_name)) != CLOG_RETURN_OK) {
        (void)strlcpy(process_name, "unknown", sizeof(process_name));
    }

    if (clog_util_build_dlt_app_id(process_name, app_id_out, app_id_out_sz) != CLOG_RETURN_OK) {
        return CLOG_RETURN_ERROR;
    }

    if (snprintf(app_description_out, app_description_out_sz, "Auto-generated by CLOG for process '%s' (pid=%ld, tid=%ld)",
             process_name, clog_util_get_pid(), clog_util_get_tid()) < 0) {
        return CLOG_RETURN_ERROR;
    }

    return CLOG_RETURN_OK;
}

void clog_util_get_timestamp(char *buffer, size_t size)
{
    time_t now;
    struct tm tm_info = {0};

    if (buffer == NULL || size == 0U) {
        return;
    }

    buffer[0] = '\0';
    now = time(NULL);

    if (localtime_r(&now, &tm_info) == NULL ||
        strftime(buffer, size, "%Y-%m-%d %H:%M:%S", &tm_info) == 0U) {
        (void)snprintf(buffer, size, "unknown-time");
    }
}
